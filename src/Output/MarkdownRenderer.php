<?php

namespace MigrationReview\Output;

use MigrationReview\Analysis\Finding;
use MigrationReview\Analysis\Severity;

/**
 * Markdown suitable for a pull request comment.
 */
class MarkdownRenderer implements Renderer
{
    public function render(array $reports): string
    {
        $out = ['## Migration review', ''];
        $total = 0;

        foreach ($reports as $report) {
            $findings = $report->sortedFindings();
            $total += count($findings);
            $icon = match ($report->highestSeverity()) {
                Severity::High => '🔴',
                Severity::Medium => '🟠',
                Severity::Low => '🔵',
                null => '✅',
            };

            $out[] = "### {$icon} `{$report->migration->name}`";
            $out[] = '';

            if ($report->aiSummary !== null) {
                $out[] = '> '.$report->aiSummary;
                $out[] = '';
            }

            if ($findings === []) {
                $out[] = 'No issues found.';
                $out[] = '';

                continue;
            }

            $out[] = '| Severity | Line | Issue |';
            $out[] = '| --- | --- | --- |';

            foreach ($findings as $finding) {
                $out[] = sprintf('| %s | %s | %s |', strtoupper($finding->severity->value), $finding->line ?? '', $this->cell($finding));
            }

            $out[] = '';

            foreach ($report->notes as $note) {
                $out[] = "_Note: {$note}_";
            }
        }

        $out[] = sprintf('<sub>%d finding%s across %d migration%s · generated by laravel-migration-review</sub>', $total, $total === 1 ? '' : 's', count($reports), count($reports) === 1 ? '' : 's');

        return implode("\n", $out)."\n";
    }

    private function cell(Finding $finding): string
    {
        $text = '**'.$finding->title.'**'.($finding->source === Finding::SOURCE_AI ? ' _(AI)_' : '')
            .'<br>'.$finding->message
            .($finding->suggestion !== null ? '<br>💡 '.$finding->suggestion : '');

        return str_replace(['|', "\n"], ['\|', ' '], $text);
    }
}
